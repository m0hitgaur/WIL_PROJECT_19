"""
Complete LangGraph Orchestrator for Financial Hybrid Vector-Graph RAG.
Optimized Dual-Process Architecture:
- System 1 (Jev): High-speed intent routing, instant advice refusal, candidate reranking, and semantic grounding.
- System 2 (Gemma:4b): Generative synthesis with compact context and short citation aliases.
- Option D Guardrails: Tier 1 Deterministic + Tier 2 Jev Noul, capped at 1 retry maximum.
- Decoupled asynchronous graph self-healing.
"""

import logging
from typing import Dict, Any, List
from langgraph.graph import StateGraph, END
import ollama
from config import settings
from agent.state import AgentState
from agent.router import agent_router
from retrieval.unified_cypher import unified_retriever, RetrievedItem
from retrieval.reranker import reranker
from agent.generator import draft_generator
from guardrails.citation_checker import citation_checker
from guardrails.hallucination_grader import hallucination_grader
from guardrails.disclaimer_injector import inject_disclaimer
from agent.self_healing import self_healing_manager

logger = logging.getLogger(__name__)


# ── Node Definitions ──────────────────────────────────────────────────────────

def condense_node(state: AgentState) -> Dict[str, Any]:
    return agent_router.condense_query(state)


def router_node(state: AgentState) -> Dict[str, Any]:
    return agent_router.route_query(state)


def route_decision(state: AgentState) -> str:
    route = state.get("route", "retrieval")
    if route in ["conversational", "advice_refusal", "retrieval"]:
        return route
    return "retrieval"


def advice_refusal_node(state: AgentState) -> Dict[str, Any]:
    """Instant refusal node complying with Australian financial advice regulations (ASIC RG 244)."""
    refusal_msg = (
        "I cannot provide personalized financial advice, investment recommendations, or portfolio allocation strategies. "
        "Under Australian financial services regulations (ASIC RG 244), I am authorized only to provide factual information "
        "and objective disclosures directly extracted from published Vanguard fund documents and Product Disclosure Statements (PDS)."
    )
    return {
        "draft_answer": refusal_msg,
        "final_answer": refusal_msg,
    }


def conversational_node(state: AgentState) -> Dict[str, Any]:
    """Direct fast chat response for greetings and non-document queries without disclaimers."""
    client = ollama.Client(host=settings.OLLAMA_BASE_URL)
    user_query = state.get("user_query", "")
    try:
        res = client.chat(
            model=settings.OLLAMA_LLM_MODEL,
            messages=[
                {
                    "role": "system",
                    "content": (
                        "You are an AI financial document assistant specialized in Australian investment funds and ETF reports. "
                        "Answer the user politely, briefly (1-2 sentences), and professionally. "
                        "Do not include any financial disclaimer or warning. Invite them to ask financial or document-specific questions."
                    ),
                },
                {"role": "user", "content": user_query},
            ],
            think=False,
            options={"num_predict": 256},
            keep_alive=-1,
        )
        answer = res.message.content.strip() if res and res.message else ""
        if not answer:
            answer = (
                "Hello! I am your Financial Document Analysis assistant. "
                "Ask me questions about Australian funds, performance, management fees, or report notes."
            )
    except Exception as e:
        logger.warning(f"Conversational node fallback: {e}")
        answer = (
            "Hello! I am your Financial Document Analysis assistant. "
            "Ask me questions about Australian funds, performance, management fees, or report notes."
        )

    # Clean any accidental disclaimer text if generated by model
    if "disclaimer" in answer.lower():
        lines = [line for line in answer.split("\n") if "disclaimer" not in line.lower()]
        cleaned_ans = "\n".join(lines).strip()
        if cleaned_ans:
            answer = cleaned_ans

    return {"final_answer": answer, "draft_answer": answer}


def retrieval_node(state: AgentState) -> Dict[str, Any]:
    query = state.get("condensed_query") or state.get("user_query", "")
    candidates = unified_retriever.retrieve(query=query, top_k=5)
    return {"retrieved_candidates": candidates}


def rerank_node(state: AgentState) -> Dict[str, Any]:
    query = state.get("condensed_query") or state.get("user_query", "")
    candidates = state.get("retrieved_candidates", [])
    top_chunks = reranker.rerank(query=query, candidates=candidates, top_n=2)
    return {"reranked_chunks": top_chunks}


def generator_node(state: AgentState) -> Dict[str, Any]:
    return draft_generator.generate(state)


def citation_check_node(state: AgentState) -> Dict[str, Any]:
    return citation_checker.check(state)


def citation_decision(state: AgentState) -> str:
    """Evaluate Tier 1 citation check result: retry (capped at 1 attempt) or proceed to Tier 2."""
    error = state.get("citation_error")
    iteration = state.get("iteration_count", 1)
    if error and iteration < 2:
        logger.info(f"Tier 1 Check failed, retrying generator (attempt {iteration + 1}): {error}")
        return "retry_generator"
    return "hallucination_grader"


def hallucination_grader_node(state: AgentState) -> Dict[str, Any]:
    return hallucination_grader.grade(state)


def hallucination_decision(state: AgentState) -> str:
    """Evaluate Tier 2 grounding check result: retry (capped at 1 attempt) or proceed to disclaimer."""
    error = state.get("hallucination_error")
    iteration = state.get("iteration_count", 1)
    if error and iteration < 2:
        logger.info(f"Tier 2 Check failed, retrying generator for grounding correction: {error}")
        return "retry_generator"
    return "disclaimer_injector"


def disclaimer_node(state: AgentState) -> Dict[str, Any]:
    return inject_disclaimer(state)


def self_healing_node(state: AgentState) -> Dict[str, Any]:
    self_healing_manager.refine_graph_async(state)
    return {}


# ── LangGraph Workflow Construction ───────────────────────────────────────────

def build_full_rag_graph() -> StateGraph:
    """Build and compile the complete closed-world RAG workflow with Option D guardrails."""
    workflow = StateGraph(AgentState)

    # Register Nodes
    workflow.add_node("condenser", condense_node)
    workflow.add_node("router", router_node)
    workflow.add_node("advice_refusal", advice_refusal_node)
    workflow.add_node("conversational", conversational_node)
    workflow.add_node("retrieval", retrieval_node)
    workflow.add_node("rerank", rerank_node)
    workflow.add_node("generator", generator_node)
    workflow.add_node("citation_check", citation_check_node)
    workflow.add_node("hallucination_grader", hallucination_grader_node)
    workflow.add_node("disclaimer_injector", disclaimer_node)
    workflow.add_node("self_healing", self_healing_node)

    # Set Entry Point & Routing
    workflow.set_entry_point("condenser")
    workflow.add_edge("condenser", "router")

    workflow.add_conditional_edges(
        "router",
        route_decision,
        {
            "advice_refusal": "advice_refusal",
            "conversational": "conversational",
            "retrieval": "retrieval",
        },
    )

    # Advice refusal routes directly to disclaimer injector
    workflow.add_edge("advice_refusal", "disclaimer_injector")
    workflow.add_edge("conversational", END)

    # Retrieval & Generation Chain
    workflow.add_edge("retrieval", "rerank")
    workflow.add_edge("rerank", "generator")
    workflow.add_edge("generator", "citation_check")

    # Option D Two-Tier Guardrail Feedback Loops (Capped at 1 retry)
    workflow.add_conditional_edges(
        "citation_check",
        citation_decision,
        {
            "retry_generator": "generator",
            "hallucination_grader": "hallucination_grader",
        },
    )

    workflow.add_conditional_edges(
        "hallucination_grader",
        hallucination_decision,
        {
            "retry_generator": "generator",
            "disclaimer_injector": "disclaimer_injector",
        },
    )

    workflow.add_edge("disclaimer_injector", "self_healing")
    workflow.add_edge("self_healing", END)

    return workflow.compile()


financial_rag_app = build_full_rag_graph()
